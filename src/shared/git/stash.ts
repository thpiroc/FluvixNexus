/**
 * 退避（stash）の一覧（Session 3-8-15）。
 *
 * ## repository.ts / status.ts / branch.ts / history.ts との分担
 *
 * repository.ts が「始められるか」、status.ts が「何が変わっているか」、
 * branch.ts が「どこへ切り替えられるか」、history.ts が「ここまで何をしてきたか」を
 * 持つのに対し、こちらは**「今どこかへ避けてあるもの」**だけを持つ。
 *
 * 相手は作業ツリーでも履歴でもない第3の置き場になる ── `refs/stash` の reflog で、
 * 記録された commit ではあるが、どのブランチからも辿れない。history.ts が
 * 「過去」を出したのに対し、こちらが出すのは**今の作業の脇に置いたもの**にあたる。
 *
 * ## `GitRepositoryState` の `ready` に入れていない
 *
 * ブランチの一覧（branch.ts）・履歴（history.ts）とまったく同じ判断で、
 * **見られている時間が違う。**
 *
 *   変更ファイル … パネルが開いている間ずっと出ている
 *   退避の一覧   … 利用者が退避の面を開いた、その間だけ
 *
 * 相乗りさせると、ファイルを保存するたびに `git stash list` を1回起動することになる。
 *
 * ## 番号（`index`）は動く ── だから hash も一緒に持つ
 *
 * ここがブランチ（名前）や commit（hash）と決定的に違うところになる。
 * `stash@{0}` は**いちばん新しい退避**を指す名前で、退避を1つ作れば全部が
 * 1つずつ後ろへずれ、1つ捨てても同じだけ前へ詰まる（実物で確かめてある。
 * main/git/gitStashRepository.test.ts）。
 *
 * つまり一覧を出してから押すまでの間に端末で `git stash` を1回打たれると、
 * **画面で選んだのとは違う退避が pop / drop される。** 番号だけを渡す形は
 * そこで嘘になるため、`shortHash`（その退避そのものを指す、動かない値）を
 * 一緒に持ち、Main が押された瞬間に突き合わせる（main/git/gitStash.ts）。
 *
 * 3-8-14 で rename に `--force` を渡す前に「相手は自分自身か」を確かめたのと
 * 同じ構えで、**戻せない操作の直前にもう一度だけ確かめる**ことになる。
 *
 * shared 層のルールどおり、このファイルは型と定数だけを持つ。
 */

/**
 * 退避1件。
 *
 * ## 載せているのは、その行に出るものだけ
 *
 * `GitCommitSummary` と同じ考え方で、**画面に出ないものは載せない**（完全な
 * hash・退避に含まれるファイルの一覧・退避したときのブランチ名の欄）。
 * どれも一覧の1行には出ず、載せれば git へ聞くことが増える。
 *
 * 例外は `index` で、これだけは**画面に出す値ではない**（出るのは並び順そのもの）──
 * pop / drop で git に渡す唯一の指し方になる。
 */
export interface GitStashEntry {
  /**
   * `stash@{N}` の N（0 がいちばん新しい）。
   *
   * **この値は次の瞬間には別のものを指しうる**（上記）。渡すときは必ず
   * `shortHash` と対で渡し、Main が突き合わせてから git を動かす。
   *
   * 文字列（`stash@{0}`）ではなく数で持つのは、境界を渡る値を
   * **他の文字と繋いで引数にしない**という線（§14.20 で `<hash>:<path>` を
   * 作らないと決めたもの）を保つため ── 検証済みの整数からは、
   * 引数として読み替えられる形が1つも作れない。
   */
  readonly index: number
  /**
   * その退避そのものの短い hash（`%h`）。
   *
   * 退避は commit なので、`GitCommitSummary.shortHash` とまったく同じ形の値に
   * なる（16進 4〜40 桁）── 通す関数も同じ `normalizeGitCommitHash` で、
   * **履歴の行を指す値の入口を2つに分けない**（main/ipc/handlers/git.ts）。
   *
   * 画面には出さない。持っているのは**押した瞬間に突き合わせる**ためだけになる。
   */
  readonly shortHash: string
  /**
   * git が付けた名乗り（`%gs`）。
   *
   * 例: `WIP on main: 1a2b3c4 直前の commit の要約`
   *
   * ## 自分で組み立てない
   *
   * 「どのブランチで」「どの commit の上で」を欄として分けて持つこともできるが、
   * そうしていない ── 退避に名前を付ける欄を作っていない（`-m` を渡さない。
   * main/git/gitCommands.ts）以上、ここに出るのは**git が決めた1つの文字列**が
   * 正本になる。分解して並べ直すと、アプリが付けた名前のように見え始める。
   *
   * 結果としてブランチ名は文の中に現れるが、それは git の名乗りの一部であって、
   * こちらが「退避したブランチ」という欄を作ったわけではない。
   */
  readonly subject: string
  /**
   * 退避した日時（epoch ミリ秒）。
   *
   * `GitCommitSummary.authoredAt` とまったく同じ扱いで、`%at`（epoch 秒）から
   * 作る ── `%ad` はリポジトリの設定（`log.date`）で形が変わり、PC ごとに
   * 違う文字列が画面に出ることになる（shared/git/history.ts）。
   */
  readonly stashedAt: number
}

/**
 * 一覧に載せる退避の上限。
 *
 * 退避は「後で戻すもの」なので、普通は数件で頭打ちになる ── それでも上限を
 * 置くのは、消さずに溜め続ける使い方が実在するため（履歴と同じく、
 * IPC を渡る配列の長さがリポジトリ次第で決まる形にしない）。
 *
 * 100 は履歴（`GIT_COMMIT_HISTORY_LIMIT`）と同じ数にしてある。**別の数に
 * する理由が無い**ものを別にすると、どちらがどちらだったかを覚えることになる。
 *
 * 超えた分は**黙って捨てない** ── 切れていることを `truncated` として返し、
 * 画面にもそう出す（ブランチ・履歴と同じ形。renderer/src/git/gitStash.ts）。
 */
export const GIT_STASH_LIMIT = 100

/**
 * 一覧を尋ねた結果。
 *
 * ## 失敗も「状態」として持つ（3-8-1 からの続き）
 *
 * 読めなかったことを `IpcResult` の失敗にしない。開いた面の中に
 * 「取得できませんでした」と出せばよいものであって、汎用のエラー文言に
 * 丸めると、利用者は**その面のどこを見ればよいか**を失う
 * （shared/git/repository.ts）。
 *
 * ## 「commit が1つも無い」でも `ready` の空になる
 *
 * 履歴（`git log`）は HEAD が無いと非0で終わるため手前で分ける必要があったが、
 * `git stash list` は**commit が1つも無いリポジトリでも 0 で終わり、空を返す**
 * （実物で確かめてある）── したがってここに分岐は要らず、空はそのまま
 * 「1件も退避していない」という正しい答えになる。
 */
export type GitStashListing =
  | {
      readonly status: 'ready'
      /** 新しい順（`stash@{0}` が先頭）。 */
      readonly entries: readonly GitStashEntry[]
      /** 上限（`GIT_STASH_LIMIT`）で切ったか。 */
      readonly truncated: boolean
    }
  /** もう一覧を出せる状態ではない（Workspace が閉じられた・リポジトリでなくなった）。 */
  | { readonly status: 'not-ready' }
  /** git を動かせた／動かせなかったに関わらず、一覧として読めなかった。 */
  | { readonly status: 'failed' }
