/**
 * commit の履歴（Session 3-8-11）。
 *
 * ## repository.ts / status.ts / branch.ts との分担
 *
 * repository.ts が「始められるか」、status.ts が「何が変わっているか」、
 * branch.ts が「どこへ切り替えられるか」を持つのに対し、こちらは
 * **「ここまで何をしてきたか」**だけを持つ。
 *
 * ここまでの Git 機能は、どれも**今の作業ツリーと index** を相手にしていた
 * （変更の一覧・差分・Stage・Commit）。履歴はそこから初めて外れる ──
 * 相手は既に記録された commit の連なりで、**アプリからは何も変えられない。**
 * 読むだけの面であることが、この型に書き込みの余地が1つも無い理由になる。
 *
 * ## `GitRepositoryState` の `ready` に入れていない
 *
 * ブランチの一覧（branch.ts）とまったく同じ判断で、**見られている時間が違う。**
 *
 *   変更ファイル … パネルが開いている間ずっと出ている
 *   履歴         … 利用者が履歴を開いた、その間だけ
 *
 * 相乗りさせると、ファイルを保存するたび（`files:changed` からの読み直し）に
 * `git log` を1回起動することになる ── 誰も見ていない一覧のために、
 * commit を 100 件読み直し続ける形になる。
 *
 * ## `git log` の出力そのものは渡らない
 *
 * 渡るのは**読み終えた後の値**（短い hash・要約・名乗り・日時・親の数）だけで、
 * git の記法（graph の罫線・`commit <hash>` の行・日付の書式）は1文字も載らない。
 * 差分で patch を渡さなかったのと同じ線になる（diff.ts）── 生の出力を渡すと、
 * 受け取った側にもう1つ解析が生まれる。
 *
 * shared 層のルールどおり、このファイルは型と定数だけを持つ。
 */

/**
 * commit 1件。
 *
 * ## 載せているのは、その行に出るものだけ
 *
 * `GitLocalBranch` が名前と印しか持たないのと同じ考え方で、**画面に出ないものは
 * 載せない。** 完全な hash・commit した人（committer）・本文（`%b`）・
 * 変更されたファイルの一覧・tag・親の hash は、どれも今回の面に出ない ──
 * 載せると、100 件ぶんの文字列を誰も読まないまま IPC の向こうへ運ぶことになる。
 *
 * 例外は `parentCount` で、これだけは**数そのものが画面に出る値ではない。**
 * 出るのは「マージ」という1語で、それを決めるのが親の数になる（下記）。
 */
export interface GitCommitSummary {
  /**
   * 短くした hash（`%h`）。
   *
   * **完全な hash（40文字）を載せていない。** 出すのは短い方だけで、
   * 短い方から長い方を組み立てる経路もアプリの中には無い ── 完全な hash を
   * 渡すと、それを指して何かを頼む欄（`git show <hash>` / チェックアウト）が
   * 欲しくなり、rev を渡せる口を作らないという線（§14.16）に触れる。
   *
   * どこまで短くするかは git が決める（リポジトリの大きさで変わる）。
   * アプリ側で桁数を決め打ちにすると、大きなリポジトリで**衝突する長さ**まで
   * 削ってしまう。
   */
  readonly shortHash: string
  /**
   * commit メッセージの1行目（`%s`）。
   *
   * 本文（2行目以降）は載せない ── 一覧の1行に収まらず、しかも
   * 「開いて読む」ための場所を作ると、それは commit 1件の詳細画面になる。
   *
   * 空文字もありうる（`--allow-empty-message` で作られた commit）。
   * 空を「読めなかった」として捨てない ── その commit は実在し、
   * 履歴から消すと**その1件だけ順番が飛ぶ**ことになる。
   */
  readonly subject: string
  /**
   * 書いた人の名前（`%an`）。
   *
   * メールアドレスは載せない（画面に出さないため）。**committer ではなく
   * author** を持つのは、`authoredAt` と揃えるためになる ── 名前と日時が
   * 別々の人・別々の瞬間のものだと、1行の中で食い違う。
   */
  readonly authorName: string
  /**
   * 書かれた日時（epoch ミリ秒）。
   *
   * ## 文字列ではなく数で持つ
   *
   * git に日付を整形させない（`%ad` を使わない）。理由は2つある。
   *
   *   - `%ad` の形はリポジトリの設定（`log.date`）で変わる。**PC ごとに
   *     違う形の文字列**が画面に出ることになる
   *   - 相対表示（「3分前」）は、受け取った側が**今**と比べなければ作れない。
   *     整形済みの文字列を受け取ると、そこからもう一度日時に戻すことになる
   *
   * 使うのは `%at`（epoch 秒）で、これは設定に左右されない生の数になる。
   * ミリ秒へ直すのは Main の読み取り側（main/git/gitOutput.ts）。
   *
   * ## timezone は載せない
   *
   * commit には書いた人の timezone（`%ai` の `+0900`）も記録されているが、
   * 載せない ── 出すのは**見ている人の時計での日時**で、それは epoch から
   * そのまま決まる。書いた人の現地時刻まで出すと、1行に2つの時刻が並ぶ。
   */
  readonly authoredAt: number
  /**
   * 親の数（`%P` の個数）。
   *
   * ## これだけは「数」を出すために載せていない
   *
   * 画面に出るのは**マージかどうか**（親が2つ以上か）の1語だけになる。
   * それでも `boolean` ではなく数で持つのは、`isMerge: true` にすると
   * **どこで決めたのかが Main の中に隠れる**ため ── 境界を渡るのは
   * git が答えた事実（親がいくつか）で、それを「マージ」と呼ぶかどうかは
   * 画面の側の判断にあたる（renderer/src/git/gitHistory.ts）。
   *
   * 親の hash そのものは載せない（`shortHash` と同じ理由で、指して何かを
   * 頼む先が無い）。0 になるのは履歴のいちばん最初の commit だけになる。
   */
  readonly parentCount: number
}

/**
 * 一覧に載せる commit の上限。
 *
 * 履歴は**上限を置かなければ際限が無い**唯一の一覧になる（変更ファイルは
 * 作業ツリーの大きさで頭打ちになり、ブランチも数千で止まる）── Linux の
 * リポジトリなら 100 万件を超える。
 *
 * 100 は「押した人が今いる場所からさかのぼって眺める」ぶんとして十分に多く、
 * IPC を1回で渡すには十分に小さい。**もっと先を見る**手立て（続きを読む・
 * 期間で絞る）は置いていない ── 増やす操作を足すなら、どこまで読んだかを
 * 覚える状態が1つ増える（docs/ARCHITECTURE.md §14.19）。
 *
 * 超えた分は**黙って捨てない。** 一覧が切れていることを `truncated` として
 * 返し、画面にもそう出す（ブランチの一覧と同じ形。branch.ts）。
 */
export const GIT_COMMIT_HISTORY_LIMIT = 100

/**
 * 履歴を尋ねた結果。
 *
 * ## 失敗も「状態」として持つ（3-8-1 からの続き）
 *
 * 読めなかったことを `IpcResult` の失敗にしない。開いた面の中に
 * 「取得できませんでした」と出せばよいものであって、汎用のエラー文言に
 * 丸めると、利用者は**その面のどこを見ればよいか**を失う
 * （shared/git/repository.ts）。
 *
 * `not-ready` を分けているのは、そこで言うことがまったく違うため ──
 * Workspace が閉じられた・リポジトリでなくなった場合、次に出るのは
 * 履歴ではなく Git パネルそのものの案内になる。
 *
 * ## 「commit が1つも無い」は失敗ではない
 *
 * `git init` の直後は HEAD の指す先がまだ無く、`git log` は**エラーで終わる。**
 * それを `failed` として出すと、初期化した直後のリポジトリで
 * 「履歴を取得できませんでした」と出ることになる ── 正しくは
 * 「まだ commit がありません」で、次の一手は下の Commit 欄にある。
 *
 * したがって Main は `git log` を動かす前に HEAD の有無を確かめ、
 * 無ければ **`ready` の空**として返す（ブランチの一覧とまったく同じ形。
 * main/git/gitHistory.ts）。
 */
export type GitCommitHistory =
  | {
      readonly status: 'ready'
      /** 新しい順（`git log` の既定の並び）。 */
      readonly commits: readonly GitCommitSummary[]
      /** 上限（`GIT_COMMIT_HISTORY_LIMIT`）で切ったか。 */
      readonly truncated: boolean
    }
  /** もう履歴を出せる状態ではない（Workspace が閉じられた・リポジトリでなくなった）。 */
  | { readonly status: 'not-ready' }
  /** git を動かせた／動かせなかったに関わらず、履歴として読めなかった。 */
  | { readonly status: 'failed' }
