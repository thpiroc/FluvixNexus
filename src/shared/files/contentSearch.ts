/**
 * ファイル本文の全文検索（Session 3-6-5）の上限と、結果の形。
 *
 * ## 名前の検索（search.ts）と別のファイルにする理由
 *
 * 3-6-4 の検索は、readdir が返した**名前**を照合するだけで済む ── 1件あたりの
 * 費用はほぼ 0 で、上限も「何件見つけたか」「何件見たか」で足りた。
 *
 * 全文検索は**1件ずつ開いて読む**。同じ「1件」でも費用の桁が違い、
 * 止めるべき理由も別のものになる。
 *
 *   名前   … 見つけた件数 / 見たエントリ数 / 深さ / 時間
 *   全文   … それに加えて **読んだファイル数** と **1ファイルの大きさ**
 *
 * search.ts の冒頭に「全文検索はここに載せない」と書いてあるのはこのためで、
 * 上限を1箇所に混ぜると、どちらの検索の歯止めなのかが値から読めなくなる。
 *
 * ## なぜ shared に置くか
 *
 * search.ts と同じ理由。**打ち切った数を画面に出すのは Renderer** で、
 * 打ち切る判断をするのは Main になる。数そのものは双方が同じものを見る必要がある。
 *
 * shared 層のルールどおり、ここには型と定数だけを置く（照合そのものは
 * Renderer 側に要らない ── 一致の位置は Main が `previewColumn` として返すため、
 * main/files/contentMatches.ts に閉じてある）。
 */

import { FILES_FILE_MAX_BYTES } from './content'

/* ------------------------------------------------------------------ 上限 */

/**
 * 1ファイルを読む上限（バイト）。
 *
 * **Editor で開ける上限（FILES_FILE_MAX_BYTES）と同じ値にしてある。**
 * 別の値にすると、次のどちらかが必ず起きる。
 *
 *   検索の上限が大きい … 見つかったのに、押すと「大きすぎて表示できません」
 *   検索の上限が小さい … 開いて Ctrl+F では見つかるのに、全体検索には出てこない
 *
 * どちらも利用者から見れば筋が通らない。「Editor で開けるものを探す」と
 * 決めておけば、見つかったものは必ず開けて、開けるものは必ず探される。
 */
export const FILE_CONTENT_SEARCH_FILE_MAX_BYTES = FILES_FILE_MAX_BYTES

/**
 * 1回の検索で中身を読むファイル数の上限。
 *
 * 走査数の上限（FILE_SEARCH_MAX_SCANNED_ENTRIES = 50,000）とは別に要る。
 * あちらは「名前を見た数」で、こちらは「開いて読んだ数」── 費用が2桁違う以上、
 * 同じ数で止めるわけにはいかない。
 *
 * 2,000 件は、`.git` / `node_modules` を外した一般的なプロジェクトの
 * ソース一式（数百〜千数百件）に対して余裕がある一方、生成物を大量に含む
 * リポジトリでは効く、という境目に置いてある。
 */
export const FILE_CONTENT_SEARCH_MAX_FILES = 2_000

/**
 * 1回の検索で返す一致の総数の上限。
 *
 * 名前の検索（500 件）より多いのは、**1行が1件になる**ため。
 * `const` のような語では1ファイルから数十件出るのが普通で、
 * 500 で切ると「ファイル3つぶんで打ち切り」になり、絞り込みの判断材料にならない。
 */
export const FILE_CONTENT_SEARCH_MAX_MATCHES = 1_000

/**
 * 1ファイルから取る一致の上限。
 *
 * 総数の上限だけでは足りない。1つの巨大なファイル（生成された定義ファイルなど）が
 * 総数を使い切ると、**他のファイルの一致が1件も出ない**。
 * ファイル単位で頭打ちにしておくと、結果が広く行き渡る。
 *
 * 打ち切ったことはファイル単位の `truncated` として返す（そのファイルの中を
 * さらに見たければ、開いて Monaco の検索を使う方が早い）。
 */
export const FILE_CONTENT_SEARCH_MAX_MATCHES_PER_FILE = 50

/**
 * 1回の検索に使ってよい時間（ミリ秒）。
 *
 * 名前の検索（4 秒）より長い。1件ごとに読み込みが挟まるため、同じ時間では
 * 見られる範囲が桁違いに狭くなる ── 短くしすぎると「毎回 time で打ち切る検索」に
 * なり、上限としての意味を失う。
 *
 * それでも上限そのものを外さないのは、**件数の上限では止まらない検索**が
 * あるため（一致が0件でも、読む対象は上限まで読み続ける）。
 */
export const FILE_CONTENT_SEARCH_TIME_BUDGET_MS = 6_000

/**
 * 一致箇所の周辺として返す文字数の上限。
 *
 * 圧縮された JavaScript のように「1行が数十万文字」のファイルは普通にある。
 * 行をそのまま返すと、IPC で運ぶ量も描く量もその行1つで決まってしまう。
 *
 * 200 文字は、Files パネルの幅（省略される）に対して十分な長さで、
 * かつ1件あたりの重さが読める大きさに収まる、という兼ね合いで置いている。
 */
export const FILE_CONTENT_SEARCH_PREVIEW_MAX_LENGTH = 200

/**
 * 一致箇所の前に含める文字数（preview を切り出すときの目安）。
 *
 * 一致を先頭に置くと「何の中で一致したか」が分からない
 * （`example` が変数名なのか文字列の中なのかは、直前の数文字で決まる）。
 */
export const FILE_CONTENT_SEARCH_PREVIEW_LEAD = 24

/** preview を切り詰めたことを示す記号（前後どちらにも付く）。 */
export const FILE_CONTENT_SEARCH_ELLIPSIS = '…'

/* ------------------------------------------------------------------ 結末 */

/**
 * 全部は見ずに打ち切った理由。
 *
 * 名前の検索（FileSearchLimit）と**別の型にしてある**。共有できるのは
 * `scanned` / `time` / `depth` の3つだけで、残りは全文検索にしか無い
 * （`files` / `matches` / `file-matches`）── 片方にしか起きない値を混ぜた型を
 * 両方で使うと、画面側で「起きえない場合」を毎回書くことになる。
 *
 * どれも失敗ではなく「ここまでしか見ていない」という事実で、
 * 利用者の次の一手は理由によって変わる。
 *   matches      … 一致が多すぎる。語を足せば済む
 *   files        … 読むファイルが多すぎる。範囲の指定が要る
 *   scanned      … 対象のファイルが多すぎる（名前の段階で打ち切った）
 *   time         … 時間が掛かりすぎた。もう一度試すと通ることもある
 *   depth        … 深すぎる場所は見ていない。そこに在るなら見つからない
 *   file-matches … どこかのファイルで、そのファイル内の上限に当たった
 */
export type FileContentSearchLimit =
  'matches' | 'files' | 'scanned' | 'time' | 'depth' | 'file-matches'

/* -------------------------------------------------------------- 結果の形 */

/**
 * 一致1件。
 *
 * ## 位置は1始まり
 *
 * Editor（Monaco）の行・桁がどちらも1始まりで、画面に出す `42:15` もその値そのもの。
 * 0 始まりで持つと、**受け渡しのたびに +1 / -1 が要る**ことになり、
 * どこかで1つずれた結果が「押すと1文字手前へ飛ぶ」形で表に出る。
 *
 * 桁は UTF-16 のコード単位で数える（JavaScript の文字列・Monaco と同じ数え方）。
 * サロゲートペア（絵文字）を含む行では、見た目の文字数とは一致しない。
 */
export interface FileContentMatch {
  /** 一致した行（1 始まり）。 */
  readonly line: number
  /** 行の中での一致の開始位置（1 始まり）。 */
  readonly column: number
  /** 一致した長さ（検索語の長さ）。 */
  readonly length: number
  /**
   * 一致箇所の周辺（1行ぶん。長い行は切り詰めてある）。
   *
   * 制御文字は空白へ置き換わり、切り詰めた側には `…` が付く。
   * **1文字を1文字へ置き換える**形でしか加工していないため、
   * `previewColumn` はこの文字列に対してそのまま使える。
   */
  readonly preview: string
  /** preview の中での一致の開始位置（1 始まり）。印を付けるために使う。 */
  readonly previewColumn: number
}

/**
 * 1ファイルぶんの一致。
 *
 * **ファイル単位にまとめた形で返す。** 平らな一覧で返して Renderer 側で
 * まとめ直す形にすると、まとめ方（同じファイルが離れて並ばないこと）が
 * 走査の順序に依存する ── 走査しているのは Main なので、
 * まとめるのも Main の側にしておく。
 *
 * 名前（`name`）を持たせているのは、開く経路がツリー・名前検索と同じ
 * `openFile({ relativePath, name })` だから（相対位置から切り出せる値だが、
 * 受け手が切り出す形にすると切り出し方が2箇所に散る）。
 */
export interface FileContentMatchFile {
  /** Workspace root からの相対位置。区切りは `/`。 */
  readonly relativePath: string
  /** ファイル名（結果の見出しと、開くときのタブ名）。 */
  readonly name: string
  /** そのファイルの中の一致（行・桁の順）。 */
  readonly matches: readonly FileContentMatch[]
  /** このファイル内の上限（FILE_CONTENT_SEARCH_MAX_MATCHES_PER_FILE）で打ち切ったか。 */
  readonly truncated: boolean
}
