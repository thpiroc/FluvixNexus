/**
 * コピー（同じものをもう1つ作る）だけが持つ値。
 *
 * ## なぜ shared に置くか
 *
 * move.ts と同じ理由による。**detail の文字列は契約の一部**で、載せるのは Main、
 * 読むのは Renderer。2箇所に同じ文字列を書くと、片方だけ直された時点で
 * 「理由が分かるはずの失敗が、理由の分からない失敗に落ちる」というずれが生まれる。
 *
 * 「コピー先が、コピーするもの自身かその中」は**移動と同じ理由**なので、
 * 定数も移動のもの（MOVE_INTO_SELF_DETAIL）をそのまま使う。値は
 * `destination-inside-source` で操作を含んでおらず、利用者の次の一手
 * （別のフォルダを選び直す）も同じ。文言だけを操作ごとに変える
 * （renderer/src/files/filesError.ts が action で分ける）。
 *
 * shared 層のルールどおり、このファイルは定数だけを持つ。
 */

/**
 * コピー元が symlink / ジャンクションだったことを表す `detail`。
 *
 * 載せるのは main/ipc/handlers/files.ts（INVALID_REQUEST の detail として）。
 * 読むのは renderer/src/files/filesError.ts。
 *
 * リンクを辿ると、**Workspace の外にある実体の中身を Workspace の中へ持ち込める。**
 * それは「Workspace の外を読まない」（ARCHITECTURE.md §9.3）の抜け道そのものなので、
 * 指し先を複製しない。リンクそのものを作り直す形にもしない ── Windows では
 * 権限が要るうえ、外を指す入口を**アプリが新しく増やす**ことになる。
 *
 * 断る側に倒しているのは、コピーが**中身を持ってくる操作**だからにほかならない。
 * 削除・改名・移動がリンクに対して通る（リンクそのものを動かすだけで、
 * 指し先には触れない）のと矛盾しない。
 */
export const COPY_LINK_SOURCE_DETAIL = 'source-is-link'

/**
 * コピーが途中で失敗し、**作りかけのものがコピー先に残っている**ことを表す `detail`。
 *
 * フォルダの再帰コピーは1回の fs 操作では終わらないため、途中で失敗しうる
 * （権限・使用中・容量）。そのとき**作りかけを消しに行かない。**
 * 完全削除の経路を持たない方針（ARCHITECTURE.md §10.2）を、
 * アプリ自身が作ったものに対しても曲げないため。
 *
 * 残ったものはツリーに現れる（`files:changed` の `created` は流す）ので、
 * 利用者が見て消せる。**何が起きたかを言わずに残す方が悪い**ため、
 * 失敗の分類（権限 / 使用中 / それ以外）とは別に、この状態を detail で伝える。
 * 分類ではなく detail にしてあるのは、原因が何であれ**次の一手が同じ**
 * （残ったものを消して、もう一度試す）ため。
 */
export const COPY_PARTIAL_DETAIL = 'copy-partially-written'
