/**
 * 「開いた後、この位置を見せてほしい」という依頼（Session 3-6-5）。
 *
 * 全文検索の結果を押したときに、ファイルを開くだけでは足りない ──
 * 3,000 行のファイルの 42 行目で一致したなら、そこが見えている必要がある。
 *
 * ## タブの状態として持たない
 *
 * `EditorTab`（editorTabsModel.ts）に「見せたい位置」を足していない。
 * タブが持つのは**開いている間ずっと正しいこと**（どのファイルか・未保存か）で、
 * 位置の依頼は**1回きり**のもの ── 一度飛んだら消える。
 * タブに載せると、タブを切り替えて戻るたびに同じ場所へ飛ばされる。
 *
 * ## 開く操作と別の値にする
 *
 * `openFile` を呼んだ後に位置を渡す、という2段構えにもしていない。
 * 開く時点ではまだ中身が届いておらず（新しいタブは 'loading' から始まる）、
 * 飛べるようになるのは Monaco に Model が載った後になる。
 * **依頼として置いておき、載った時点で受け取る**形にすると、
 * 「新しく開いた」「既に開いていた」の区別が要らなくなる
 * （どちらも同じ1つの経路で飛ぶ）。
 *
 * 受け取る側は monaco/MonacoEditor.tsx で、受け取ったら `consumeReveal` で消す。
 */

/** 見せてほしい位置（行・桁は1始まり。shared/files/contentSearch.ts と同じ数え方）。 */
export interface EditorRevealRequest {
  /** 対象のファイル（Workspace root からの相対位置）。 */
  readonly relativePath: string
  readonly line: number
  readonly column: number
  /**
   * 選択して見せる長さ（0 ならカーソルを置くだけ）。
   *
   * 一致した範囲をそのまま選択状態にすると、飛んだ先で**どれが一致なのか**が
   * 一目で分かる（検索結果の preview に付けた印と、同じ範囲になる）。
   */
  readonly length: number
  /**
   * 依頼ごとに変わる値。
   *
   * 同じファイルの同じ位置を続けて押した場合でも、**別の依頼として扱う**必要がある
   * （2回目に何も起きないと、押したのに反応しないように見える）。
   * React の依存としても、これが変わることが「新しい依頼が来た」の合図になる。
   */
  readonly token: number
}
