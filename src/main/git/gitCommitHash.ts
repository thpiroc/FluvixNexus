/**
 * 短い commit hash を、git の引数に載せてよい形へ通す（Session 3-8-12）。
 *
 * gitPathspec.ts が「位置」に対して行っていることを、**rev に対して**行う1枚に
 * なる。3-8-11 まで rev は1つも境界を渡らなかった（履歴の要求は `void`）が、
 * commit 1件の詳細では**どの commit かを言わなければ始まらない**ため、
 * ここで初めて外から rev が届く。
 *
 * fs にも child_process にも触れない（テストできる形にしておく）。
 *
 * ## 「rev を渡せる欄」ではなく「16進の並びを渡せる欄」にしてある
 *
 * git の rev 表記は、それ自体が小さな言語になっている。
 *
 * ```
 * HEAD~5            さかのぼる
 * main@{yesterday}  reflog を時刻で引く
 * :/直した          メッセージを正規表現で探す
 * HEAD:path         commit ではなく blob を指す
 * @{-1}             直前に居たブランチ
 * ```
 *
 * どれも「履歴に出した1行を指す」ためには要らない。通すのを**16進 4〜40 桁**に
 * 限ることで、上のどれも書けなくなる ── 危ないものを1つずつ弾くのではなく、
 * 通る形を1つに決める（3-8-3 の pathspec と同じ構え）。
 *
 * ## 桁の下限を 4 にしている
 *
 * git 自身が `core.abbrev` の下限として 4 を使う（`%h` がそれより短く
 * なることは無い）。下限を置くのは、**1〜3 桁では実在するリポジトリでほぼ
 * 必ず曖昧になる**ため ── 曖昧な rev は git が断るので通しても壊れないが、
 * 断られる形をわざわざ引数に載せる意味が無い。
 *
 * 上限の 40 は SHA-1 の完全な hash の桁数になる。SHA-256 のリポジトリ
 * （64 桁）でも、`%h` が返すのは短くした方だけなので、この欄に 40 桁を
 * 超える値が届く経路は無い ── **長い方を渡せる欄は今も作っていない**
 * （shared/git/commitDetail.ts）。
 *
 * ## 大文字を通さない
 *
 * `%h` が返すのは常に小文字で、git も小文字で解く。大文字を受け取って
 * 小文字へ直す形にすると、**「画面に出ていた文字列」以外も通る**ことになる ──
 * この欄に届いてよいのは、履歴の行がそのまま持っていた文字列だけになる。
 */

/** 16進 4〜40 桁（小文字のみ）。 */
const COMMIT_HASH = /^[0-9a-f]{4,40}$/

/**
 * 通してよい形なら、その文字列を返す。通せなければ null。
 *
 * `normalizeGitPathspec` と違い、**直す処理を1つも持たない**（trim も
 * 小文字化もしない）。位置は区切りの表記ゆれ（`\` と `/`）が正当に起こりうる
 * のに対し、hash は git が返した文字列がそのまま往復するだけで、
 * 途中で形が変わる理由が無い ── 直してから通す形にすると、
 * 「直せば通るもの」がこの欄の入口になる。
 */
export function normalizeGitCommitHash(raw: unknown): string | null {
  if (typeof raw !== 'string') {
    return null
  }

  return COMMIT_HASH.test(raw) ? raw : null
}
