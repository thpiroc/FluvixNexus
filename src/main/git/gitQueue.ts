/**
 * git を「常に1本だけ」動かすための順番待ち（Session 3-8-3）。
 *
 * ## なぜ要るのか
 *
 * Session 3-8-2 までの git は読み取りだけで、同時に2本走っても互いに影響しなかった。
 * 3-8-3 で index に**書き込む**操作が入ると、話が変わる。
 *
 *   - `git add` は `.git/index.lock` を取る。取り合いになった方は
 *     `Unable to create '.../index.lock': File exists` で失敗する
 *   - 利用者は行を2つ続けて押せる。押した2つが同時に走れば、片方が理由も無く失敗する
 *   - 操作と、その直後の status の読み直しの間に別の操作が挟まると、
 *     **押した操作の結果として出ている一覧が、別の瞬間の写し**になる
 *
 * ボタンを disabled にするだけでは足りない。Renderer 側の抑止は
 * 「同じ行の二度押し」を止めるためのもので、**別の行・別の契機（`files:changed` に
 * よる自動の読み直し）から来た git まで止められない。** 順番を決めるのは
 * git を動かす側、つまり Main になる。
 *
 * ## 弾かずに、並ばせる
 *
 * 「走っている間は断る」形にしない。断ると、利用者から見て**押したのに
 * 何も起きない**が起きる（しかも、いつ押せるようになるかが分からない）。
 * 並ばせておけば、押した順に必ず効く。
 *
 * ## 束ねる単位は「1回の git」ではなく「1つの仕事」
 *
 * `runGit` の中で待たせる形にしなかったのは、それだと
 * 「add してから status を読み直す」の**間に割り込まれる**ため。
 * 仕事の側（`describeGitRepository` / `applyGitStage`）がまるごと1枠を取る。
 *
 * その代わり、**枠の中でこの関数を呼んではいけない**（自分の番が終わるまで
 * 次が始まらないので、待ち続けることになる）。呼び出し口を
 * `gitRepository.ts` / `gitStage.ts` の公開関数だけに絞り、
 * 中で使う読み取りは待たない形（`readGitRepositoryOutcome`）で分けてある。
 */

/**
 * 直前までに積まれた仕事の列の末尾。
 *
 * 失敗も含めて必ず解決する形（`catch` で潰した写し）を繋いでいく ──
 * 途中の仕事が失敗したときに列そのものが止まると、以降の Git 操作が
 * すべて動かなくなる。失敗の中身は呼び出し側が受け取るので、ここでは捨ててよい。
 */
let tail: Promise<unknown> = Promise.resolve()

/**
 * 前の仕事が終わってから `task` を動かす。
 *
 * 例外は素通しする（この関数が意味を足すのは順番だけで、結末は変えない）。
 */
export function runGitExclusively<T>(task: () => Promise<T>): Promise<T> {
  const result = tail.then(task)

  tail = result.catch(() => undefined)

  return result
}
